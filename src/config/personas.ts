/**
 * Persona registry — 8 pixel-art founders the player can pick from
 * during onboarding. Each persona has:
 *   - a stable `id` (matches the Convex schema literal union)
 *   - a display name + tagline + archetype description for the picker UI
 *   - an accent color used for hover / active glow in the picker and for
 *     the venture HUD when this persona is active
 *   - asset paths under public/assets/personas/<id>/
 *
 * File layout expected on disk (drop PixelLab exports here):
 *   public/assets/personas/<id>/idle.png       — horizontal spritesheet
 *   public/assets/personas/<id>/walk.png       — horizontal spritesheet
 *   public/assets/personas/<id>/portrait.png   — 96×96 selection tile art
 *
 * See public/assets/personas/README.md for the full drop guide.
 */

export type PersonaId =
  | "arcanist"
  | "alchemist"
  | "artisan"
  | "drifter"
  | "oracle"
  | "engineer"
  | "healer"
  | "pathfinder";

export interface Persona {
  id: PersonaId;
  displayName: string;
  tagline: string;
  description: string;
  /** Hex accent colour used for hover glow + HUD tint. */
  accent: string;
  /** Emoji shown in tiny HUD chips when the sprite isn't loaded. */
  emoji: string;
  /** Frame counts and layout for the map spritesheet. */
  sprite: {
    /** Native frame width in the spritesheet (pixels). */
    frameWidth: number;
    /** Native frame height in the spritesheet (pixels). */
    frameHeight: number;
    /** Number of frames in the idle strip. */
    idleFrames: number;
    /** Frames-per-second for the idle animation. */
    idleFps: number;
    /** Number of frames in the walk strip. */
    walkFrames: number;
    /** Frames-per-second for the walk animation. */
    walkFps: number;
  };
  /** Public URL paths — resolved by Next.js from /public. */
  assets: {
    idle: string;
    walk: string;
    portrait: string;
  };
  /**
   * Optional extended animation set — 4-direction walk + combat states.
   * When present, the Phaser scene loads directional walk sheets + combat
   * one-shots (attack/hurt/defeat/victory) instead of the legacy 2-anim
   * (idle/walk) fallback. Only personas whose full spritesheet family has
   * been generated (e.g. Pixellab pipeline for Alchemist) set this.
   */
  extended?: {
    /** Native frame width/height for the extended set (usually 88 or 92). */
    frameWidth: number;
    frameHeight: number;
    /** Frames-per-second for each anim family. */
    idleFps: number;
    walkFps: number;
    combatFps: number;
    /** Frame counts per sheet (all sheets usually have the same count). */
    idleFrames: number;
    walkFrames: number;
    attackFrames: number;
    hurtFrames: number;
    defeatFrames: number;
    victoryFrames: number;
    /** Asset paths — one sheet per anim. Auto-derived by extendedAssetsFor. */
    assets: {
      idle: string;
      walkNorth: string;
      walkSouth: string;
      walkEast: string;
      walkWest: string;
      attack: string;
      hurt: string;
      defeat: string;
      victory: string;
    };
    /** Optional list of clip names that were NOT generated for this
     *  persona (e.g. Oracle was only partially generated by Pixellab
     *  and lacks defeat / victory / walk-* sheets). Consumers should
     *  fall back to the `idle` sheet when a listed clip is requested. */
    missingClips?: readonly (
      | "walk-north"
      | "walk-south"
      | "walk-east"
      | "walk-west"
      | "attack"
      | "hurt"
      | "defeat"
      | "victory"
    )[];
  };
}

/** Default sprite config — PRD spec: 32×48 tile, 4-frame idle @ 4fps, 6-frame walk @ 8fps.
 *  Individual personas can override any field if the PixelLab export
 *  used different frame counts. */
const DEFAULT_SPRITE = {
  frameWidth: 32,
  frameHeight: 48,
  idleFrames: 4,
  idleFps: 4,
  walkFrames: 6,
  walkFps: 8,
} as const;

/** Build the asset paths for a persona from its id. */
function assetsFor(id: PersonaId): Persona["assets"] {
  const base = `/assets/personas/${id}`;
  return {
    idle: `${base}/idle.png`,
    walk: `${base}/walk.png`,
    portrait: `${base}/portrait.png`,
  };
}

/** Build the extended-anim asset paths (Pixellab-generated pipeline). */
function extendedAssetsFor(id: PersonaId): NonNullable<Persona["extended"]>["assets"] {
  const base = `/assets/personas/${id}`;
  return {
    idle: `${base}/idle.png`,
    walkNorth: `${base}/walk-north.png`,
    walkSouth: `${base}/walk-south.png`,
    walkEast: `${base}/walk-east.png`,
    walkWest: `${base}/walk-west.png`,
    attack: `${base}/attack.png`,
    hurt: `${base}/hurt.png`,
    defeat: `${base}/defeat.png`,
    victory: `${base}/victory.png`,
  };
}

