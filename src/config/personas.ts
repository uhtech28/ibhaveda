/** The 7 second-wave personas were generated with slightly LARGER frames
 *  (92×92 instead of the alchemist's 88×88). Everything else — 9 frames
 *  per sheet, same fps — is identical. */
function makeExtended92(id: PersonaId): NonNullable<Persona["extended"]> {
  return {
    frameWidth: 92,
    frameHeight: 92,
    idleFps: 6,
    walkFps: 10,
    combatFps: 12,
    idleFrames: 9,
    walkFrames: 9,
    attackFrames: 9,
    hurtFrames: 9,
    defeatFrames: 9,
    victoryFrames: 9,
    assets: extendedAssetsFor(id),
  };
}

