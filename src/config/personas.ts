/** O(1) lookup by id. */
const PERSONAS_BY_ID: Record<PersonaId, Persona> = PERSONAS.reduce(
  (acc, p) => ({ ...acc, [p.id]: p }),
  {} as Record<PersonaId, Persona>,
);

export function getPersona(id: PersonaId | null | undefined): Persona {
  if (id && PERSONAS_BY_ID[id]) return PERSONAS_BY_ID[id];
  // Sensible default — alchemist ships with the full Pixellab
  // spritesheet set (idle + 4-direction walk + combat states), so
  // unpicked users still get rich animations for the demo.
  return PERSONAS_BY_ID.alchemist;
}

export function isValidPersonaId(id: string | null | undefined): id is PersonaId {
  return !!id && Object.prototype.hasOwnProperty.call(PERSONAS_BY_ID, id);
}

/** Legacy male/female → persona fallback so pre-existing accounts get a
 *  sane default when we migrate off the old personaGender field. */
export function legacyGenderToPersonaId(
  gender: "male" | "female" | null | undefined,
): PersonaId {
  if (gender === "female") return "healer";
  return "artisan";
}
